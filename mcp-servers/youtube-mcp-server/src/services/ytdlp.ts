import { execFile } from "node:child_process";
import { mkdtemp, readdir, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import type { TranscriptCue } from "../types.js";

const execFileAsync = promisify(execFile);

/**
 * Caption text for videos the authorized account does not own.
 *
 * The official `captions.download` endpoint cannot serve these: it enforces
 * ownership, not authentication, so any other account's video returns 403. The
 * public timedtext URL embedded in the watch page is also closed — it answers
 * 200 with an empty body unless the request carries a proof-of-origin token
 * bound to a real player session. A cold-start PoToken is not enough; the
 * token has to be attested, which means solving a BotGuard challenge.
 *
 * yt-dlp already does all of that and tracks YouTube's changes upstream, so
 * this module shells out to it rather than reimplementing the challenge.
 *
 * Requires a JS runtime on PATH for the challenge step — yt-dlp reports
 * `[jsc:deno] Solving JS challenges using deno`. Homebrew installs deno as a
 * yt-dlp dependency; without it the subtitle file is never written.
 */

const YTDLP_TIMEOUT_MS = 120_000;
/** yt-dlp writes to disk, so this only caps its own stdout/stderr. */
const MAX_OUTPUT_BYTES = 4 * 1024 * 1024;

export interface YtdlpTranscript {
  cues: TranscriptCue[];
  /** Language actually written, taken from the output filename. */
  language: string;
  /** True when the cues came from the auto-generated (ASR) track. */
  isAutoGenerated: boolean;
}

export class YtdlpError extends Error {
  constructor(
    message: string,
    readonly kind: "missing" | "noSubtitles" | "failed" | "timeout",
  ) {
    super(message);
    this.name = "YtdlpError";
  }
}

/**
 * Whether yt-dlp is callable, resolved once per process.
 *
 * Cached as the promise rather than the result so concurrent callers share a
 * single probe instead of each spawning one.
 */
let probe: Promise<boolean> | null = null;

export function ytdlpAvailable(): Promise<boolean> {
  probe ??= execFileAsync("yt-dlp", ["--version"], { timeout: 15_000 })
    .then(() => true)
    .catch(() => false);
  return probe;
}

/** Reset the cached probe. Tests only. */
export function resetYtdlpProbe(): void {
  probe = null;
}

interface Json3Event {
  tStartMs?: number;
  dDurationMs?: number;
  segs?: Array<{ utf8?: string }>;
}

/**
 * Parse yt-dlp's `json3` subtitle output into cues.
 *
 * json3 is YouTube's native caption format, preferred here over SRT because it
 * carries millisecond timings directly and needs no timecode reparsing. Events
 * without text segments are padding and are dropped — ASR tracks in particular
 * emit empty events between phrases.
 */
export function parseJson3(raw: string): TranscriptCue[] {
  let parsed: { events?: Json3Event[] };
  try {
    parsed = JSON.parse(raw) as { events?: Json3Event[] };
  } catch (error) {
    throw new YtdlpError(
      `yt-dlp wrote a subtitle file that is not valid json3: ${
        error instanceof Error ? error.message : String(error)
      }`,
      "failed",
    );
  }

  const cues: TranscriptCue[] = [];
  for (const event of parsed.events ?? []) {
    const text = (event.segs ?? [])
      .map((seg) => seg.utf8 ?? "")
      .join("")
      .replace(/\s+/g, " ")
      .trim();
    if (!text) continue;
    cues.push({
      start: (event.tStartMs ?? 0) / 1000,
      duration: (event.dDurationMs ?? 0) / 1000,
      text,
    });
  }
  return cues;
}

/**
 * Run yt-dlp for one subtitle kind and return the cues it wrote.
 *
 * `auto` picks between the publisher's uploaded track (`--write-subs`) and the
 * ASR track (`--write-auto-subs`). They are requested in separate runs on
 * purpose: yt-dlp names both output files `<id>.<lang>.json3`, so asking for
 * both at once makes it impossible to tell from disk which one you got.
 */
async function runOnce(
  videoId: string,
  langs: string[],
  auto: boolean,
): Promise<{ cues: TranscriptCue[]; language: string } | null> {
  const dir = await mkdtemp(join(tmpdir(), "yt-mcp-"));
  try {
    const args = [
      "--skip-download",
      auto ? "--write-auto-subs" : "--write-subs",
      "--sub-langs",
      langs.join(","),
      "--sub-format",
      "json3",
      "--no-playlist",
      "--no-warnings",
      "--no-progress",
      "-o",
      join(dir, "cap"),
      // execFile passes argv directly — no shell, so the id cannot inject.
      `https://www.youtube.com/watch?v=${videoId}`,
    ];

    try {
      await execFileAsync("yt-dlp", args, {
        timeout: YTDLP_TIMEOUT_MS,
        maxBuffer: MAX_OUTPUT_BYTES,
      });
    } catch (error) {
      const err = error as NodeJS.ErrnoException & { killed?: boolean; stderr?: string };
      if (err.code === "ENOENT") {
        throw new YtdlpError("yt-dlp is not installed or not on PATH.", "missing");
      }
      if (err.killed) {
        throw new YtdlpError(
          `yt-dlp timed out after ${YTDLP_TIMEOUT_MS / 1000}s.`,
          "timeout",
        );
      }
      // A missing track is not a failure of the run; the caller may retry the
      // other kind. Anything else is surfaced with yt-dlp's own message.
      const stderr = (err.stderr ?? "").trim();
      if (/no (subtitles|automatic captions)/i.test(stderr)) return null;
      throw new YtdlpError(
        `yt-dlp failed: ${stderr.split("\n").slice(-3).join(" ").slice(0, 400) || err.message}`,
        "failed",
      );
    }

    const written = (await readdir(dir)).filter((name) => name.endsWith(".json3"));
    if (!written.length) return null;

    // Sorted so that a multi-language run ("all") picks deterministically
    // rather than depending on directory order.
    const file = written.sort()[0] as string;
    const cues = parseJson3(await readFile(join(dir, file), "utf8"));
    if (!cues.length) return null;

    // yt-dlp names the file "cap.<lang>.json3", which is the only place the
    // language actually delivered is recorded — it can differ from what was
    // requested when --sub-langs was a wildcard.
    const language = /^cap\.(.+)\.json3$/.exec(file)?.[1] ?? langs[0] ?? "unknown";
    return { cues, language };
  } finally {
    await rm(dir, { recursive: true, force: true }).catch(() => {});
  }
}

/**
 * Which subtitle sources to try, in order.
 *
 * Each entry is one yt-dlp run: `langs` is passed to --sub-langs and `auto`
 * chooses ASR over the uploaded track. The first run that yields cues wins.
 */
export interface Attempt {
  langs: string[];
  auto: boolean;
  /** Language reported back to the caller when this attempt succeeds. */
  label: string;
}

/**
 * Decide the order in which to try subtitle sources for a requested language.
 *
 * The policy is "clean source over literal compliance": a publisher-authored
 * track always beats YouTube's machine translation into the requested
 * language, because that translation is applied to an ASR transcript and the
 * two error rates compound — names, numbers, and technical terms degrade
 * badly. Clean English keeps them intact and can be translated downstream with
 * the full document as context, so it is preferred even when the caller asked
 * for something else. The response reports the language actually delivered, so
 * a caller that wanted `tr` can see it received `en` and act accordingly.
 *
 * Known trade-off in step 3: `--write-auto-subs --sub-langs en` is the original
 * speech recognition for an English video, but YouTube's English *translation*
 * for a video in another language, and yt-dlp cannot distinguish the two. It is
 * ordered ahead of ASR in the requested language because English-source video
 * is the common case here. For a Turkish video with `language: "tr"`, steps 1–3
 * can therefore yield translated English before step 4 reaches the original
 * Turkish ASR. Reordering 3 and 4 flips which case pays that cost; step 2
 * already covers the common path, so step 3 is rarely reached at all.
 *
 * @param language BCP-47 code the caller asked for, or undefined for no preference.
 * @returns Attempts in priority order; the first yielding cues is used.
 */
export function planAttempts(language: string | undefined): Attempt[] {
  const preferred = language?.trim().toLowerCase();

  // No preference: take whatever the publisher actually uploaded. "all" is safe
  // with --write-subs because it matches only real uploaded tracks, not the
  // ~100 machine translations that --write-auto-subs would expand to.
  if (!preferred) {
    return [
      { langs: ["all"], auto: false, label: "original" },
      { langs: ["en"], auto: true, label: "en" },
    ];
  }

  const attempts: Attempt[] = [
    // 1. Uploaded track in the requested language — publisher-authored, ideal.
    { langs: [preferred], auto: false, label: preferred },
  ];

  if (preferred !== "en") {
    // 2. Uploaded English, chosen over a machine translation into `preferred`.
    attempts.push({ langs: ["en"], auto: false, label: "en" });
  }

  // 3. Speech recognition rather than translation — see the trade-off above.
  attempts.push({ langs: ["en"], auto: true, label: "en" });

  if (preferred !== "en") {
    // 4. Last resort: ASR in the requested language. Reached only when the
    //    video publishes nothing in English, which usually means it is not an
    //    English video — so this is likely the original audio, not a
    //    translation.
    attempts.push({ langs: [preferred], auto: true, label: preferred });
  }

  return attempts;
}

/**
 * Fetch a transcript for any public video, owned or not.
 *
 * Walks `planAttempts` in order and returns the first source that yields cues.
 */
export async function fetchTranscript(
  videoId: string,
  language: string | undefined,
): Promise<YtdlpTranscript> {
  const attempts = planAttempts(language);
  const tried: string[] = [];

  for (const attempt of attempts) {
    const result = await runOnce(videoId, attempt.langs, attempt.auto);
    tried.push(`${attempt.langs.join("/")}${attempt.auto ? " (auto)" : ""}`);
    if (result) {
      return {
        cues: result.cues,
        // What arrived, not what was asked for — the two differ whenever the
        // plan fell through to a later attempt.
        language: result.language || attempt.label,
        isAutoGenerated: attempt.auto,
      };
    }
  }

  throw new YtdlpError(
    `No subtitle track produced text for ${videoId}. Tried: ${tried.join(", ")}.`,
    "noSubtitles",
  );
}
