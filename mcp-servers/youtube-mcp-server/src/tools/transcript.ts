/** Render seconds as m:ss / h:mm:ss for cue timestamps. */
function stamp(seconds: number): string {
  const total = Math.floor(seconds);
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const pad = (n: number) => String(n).padStart(2, "0");
  return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${m}:${pad(s)}`;
}

/**
 * Download one caption track's text.
 *
 * This is the only call in the server that uses OAuth rather than the API key,
 * because captions.download refuses keys outright: "API keys are not supported
 * by this API. Expected OAuth2 access token ... that assert a principal."
 * Ownership, not merely authentication, is what it enforces — a valid token for
 * an account that does not own the video gets 403.
 */
async function downloadTrack(trackId: string, format: string): Promise<string> {
  const token = await getAccessToken();
  const url = new URL(`${API_BASE_URL}/captions/${encodeURIComponent(trackId)}`);
  url.searchParams.set("tfmt", format);

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

  let response: Response;
  try {
    response = await fetch(url, {
      signal: controller.signal,
      headers: { Authorization: `Bearer ${token}` },
    });
  } catch (error) {
    if (error instanceof Error && error.name === "AbortError") {
      throw new YouTubeApiError(408, "timeout", "Caption download timed out.");
    }
    throw new YouTubeApiError(
      0,
      "networkError",
      `Could not reach the caption endpoint: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
  } finally {
    clearTimeout(timer);
  }

  if (!response.ok) {
    const detail = await response.text().catch(() => "");
    let reason = "captionDownloadFailed";
    try {
      reason =
        (JSON.parse(detail) as { error?: { errors?: Array<{ reason?: string }> } }).error
          ?.errors?.[0]?.reason ?? reason;
    } catch {
      // Non-JSON body; keep the generic reason.
    }
    if (response.status === 403) {
      throw new YouTubeApiError(
        403,
        "notVideoOwner",
        "The authorized account does not own this video. captions.download serves caption " +
          "text only to the video's owner — there is no scope or consent screen that grants " +
          "access to someone else's captions. This tool works on your own uploads only.",
      );
    }
    throw new YouTubeApiError(response.status, reason, detail.slice(0, 300) || response.statusText);
  }

  return response.text();
}

interface RenderOptions {
  include_timestamps: boolean;
  max_cues: number;
  response_format: ResponseFormat;
}

/**
 * Shape and render cues identically whichever path produced them.
 *
 * Both paths converge here so that switching between yt-dlp and
 * captions.download changes only `source` in the payload, never the structure
 * a caller has to parse.
 */
function renderTranscript(
  result: {
    videoId: string;
    source: "yt-dlp" | "captions.download";
    language: string;
    trackId?: string;
    isAutoGenerated: boolean;
    cues: TranscriptCue[];
  },
  options: RenderOptions,
) {
  const clipped = result.cues.slice(0, options.max_cues);
  const last = clipped[clipped.length - 1];

  const payload = {
    video_id: result.videoId,
    source: result.source,
    language: result.language,
    ...(result.trackId ? { track_id: result.trackId } : {}),
    is_auto_generated: result.isAutoGenerated,
    cue_count: clipped.length,
    duration_seconds: last ? Math.round(last.start + last.duration) : 0,
    truncated: result.cues.length > clipped.length,
    cues: clipped,
    url: videoUrl(result.videoId),
  };

  return respond(
    payload,
    (p) => {
      const lines = [
        `# Transcript — ${p.video_id} (${p.language}${
          p.is_auto_generated ? ", auto-generated" : ""
        })`,
        "",
        `${p.cue_count} cues · ${stamp(p.duration_seconds)} · via ${p.source}`,
        "",
      ];
      for (const cue of p.cues) {
        lines.push(options.include_timestamps ? `[${stamp(cue.start)}] ${cue.text}` : cue.text);
      }
      if (p.truncated) {
        lines.push("", `_Truncated at ${p.cue_count} cues — raise max_cues for more._`);
      }
      return lines.join("\n");
    },
    options.response_format,
    "cues",
  );
}

export function registerTranscriptTool(server: McpServer): void {
  server.registerTool(
    "youtube_get_transcript",
    {
      title: "Get Video Transcript",
      description: `Download a video's caption text as timestamped cues. Works on any public video when yt-dlp is installed.

Two paths, tried in this order:

  1. yt-dlp (preferred, no quota cost, any public video). Requires \`yt-dlp\` on PATH plus a JS runtime for YouTube's challenge step — \`brew install yt-dlp\` supplies both, since deno comes along as a dependency. This path exists because neither official route reaches other people's captions: captions.download enforces ownership, and the public timedtext URL answers 200 with an empty body without an attested proof-of-origin token.

  2. captions.download via OAuth (fallback, YOUR OWN uploads only). Used when yt-dlp is unavailable. Costs 50 quota units for the track lookup plus 200 for the download, and returns 403 for any video the authorized account does not own. Set up with \`node scripts/authorize.mjs\`, then export YOUTUBE_OAUTH_CLIENT_ID, YOUTUBE_OAUTH_CLIENT_SECRET, and YOUTUBE_OAUTH_REFRESH_TOKEN.

The response reports which path produced the text in \`source\`. If both are unavailable, say the transcript could not be retrieved — do not infer content from the title and description.

Args:
  - video_id (string): 11-character video ID, from a video you own
  - language (string): Preferred BCP-47 code, e.g. 'en', 'tr'. Falls back to the first track.
  - include_timestamps (boolean): Prefix each markdown line with its timecode (default: true)
  - max_cues (number): Cap cues returned, 1-5000 (default: 1000)
  - response_format ('markdown' | 'json'): Output format (default: 'markdown')

Returns JSON of shape:
  {
    "video_id": string,
    "source": string,             // "yt-dlp" or "captions.download"
    "language": string,           // Language actually returned
    "track_id": string,           // Only on the captions.download path
    "is_auto_generated": boolean, // true when the track is ASR rather than uploaded
    "cue_count": number,
    "duration_seconds": number,
    "truncated": boolean,
    "cues": [ { "start": number, "duration": number, "text": string } ],
    "url": string
  }

Examples:
  - "Summarize this video" -> video_id="rKV5JcALQoQ"
  - "What did I say about pricing in that video?" -> video_id="...", then search the cues
  - "Transcript in Turkish" -> language="tr"
  - Don't use when: you only need to know which languages exist — use youtube_list_caption_tracks (no yt-dlp needed)

Error Handling:
  - "yt-dlp is not installed" plus an unowned video means neither path applies; report that rather than guessing at content
  - "No subtitle track produced text" means the video publishes no usable captions, not that the fetch broke
  - "The authorized account does not own this video" (403) can only come from the fallback path
  - "The refresh token was rejected" usually means the consent screen is still in Testing mode, where refresh tokens expire after 7 days`,
      inputSchema: {
        video_id: videoIdParam,
        language: z
          .string()
          .min(2, "language must be a BCP-47 code such as 'en' or 'tr'")
          .max(10)
          .optional()
          .describe("Preferred caption language code; falls back to the first available track"),
        include_timestamps: z
          .boolean()
          .default(true)
          .describe("Prefix each markdown line with its timecode"),
        max_cues: z
          .number()
          .int()
          .min(1)
          .max(5000)
          .default(1000)
          .describe("Maximum cues to return before truncating"),
        response_format: responseFormatParam,
      },
      annotations: {
        readOnlyHint: true,
        destructiveHint: false,
        idempotentHint: true,
        openWorldHint: true,
      },
    },
    async (params) => {
      try {
        // Path 1 — yt-dlp. Works for any public video and costs no quota, so it
        // is tried first whenever the binary is present.
        if (await ytdlpAvailable()) {
          try {
            const fetched = await fetchTranscript(params.video_id, params.language);
            return renderTranscript(
              {
                videoId: params.video_id,
                source: "yt-dlp",
                language: fetched.language,
                isAutoGenerated: fetched.isAutoGenerated,
                cues: fetched.cues,
              },
              params,
            );
          } catch (error) {
            // "This video has no captions" is a final answer — falling back to
            // captions.download would only turn it into a confusing 403. Any
            // other failure (timeout, YouTube change) is worth retrying on the
            // official path, which may still work for the user's own uploads.
            if (error instanceof YtdlpError && error.kind === "noSubtitles") {
              return errorResult(`Error: ${error.message}`);
            }
          }
        }

        // Path 2 — captions.download. Own uploads only.
        if (!oauthConfigured()) {
          return errorResult(
            `Error: yt-dlp is unavailable and OAuth is not configured — missing ${missingOAuthVars().join(", ")}. ` +
              "Caption text cannot be downloaded with an API key alone. Either install yt-dlp " +
              "(`brew install yt-dlp`), which works for any public video, or run " +
              "`node scripts/authorize.mjs` to authorize the account that owns the video.",
          );
        }

        // The track list comes from the API-key path; only the download needs OAuth.
        const listed = await ytRequest<ApiListResponse<CaptionItem>>("captions", {
          part: "snippet",
          videoId: params.video_id,
        });

        const tracks = listed.items ?? [];
        if (!tracks.length) {
          return errorResult(
            `Error: Video ${params.video_id} publishes no caption tracks, so there is no transcript to download.`,
          );
        }

        const chosen =
          (params.language
            ? tracks.find((track) => track.snippet?.language === params.language)
            : undefined) ?? tracks[0];

        if (!chosen?.id) {
          const available = tracks.map((track) => track.snippet?.language ?? "?").join(", ");
          return errorResult(
            `Error: No '${params.language}' caption track on ${params.video_id}. Available: ${available}.`,
          );
        }

        const srt = await downloadTrack(chosen.id, "srt");
        const cues: TranscriptCue[] = parseCaptions(srt);

        if (!cues.length) {
          return errorResult(
            `Error: The caption track downloaded but parsed to zero cues (${srt.length} bytes). ` +
              "The track may be empty or in an unexpected format.",
          );
        }

        return renderTranscript(
          {
            videoId: params.video_id,
            source: "captions.download",
            language: chosen.snippet?.language ?? params.language ?? "unknown",
            trackId: chosen.id,
            isAutoGenerated: chosen.snippet?.trackKind === "asr",
            cues,
          },
          params,
        );
      } catch (error) {
        return errorResult(describeError(error));
      }
    },
  );
}
