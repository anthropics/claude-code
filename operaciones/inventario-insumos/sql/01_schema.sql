-- ============================================================
-- DESPLEGADO en el proyecto Supabase `gp-inventario` (ref dflfvqiwvwvpzspspjfd).
-- Este archivo refleja el schema REAL en producción (IDs int, sucursales,
-- rutas/servicios). No usa `ordenes_trabajo` (esa tabla no existe en GP):
-- el registro de rutas completadas es `rutas` + `servicios`.
--
-- Migración aplicada: insumos_inventario_tablas
-- ============================================================

-- 1) Catálogo de insumos
CREATE TABLE IF NOT EXISTS insumos (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku            TEXT UNIQUE NOT NULL,
  nombre         TEXT NOT NULL,
  categoria      TEXT NOT NULL CHECK (categoria IN ('desinfectante','papel','gel_jabon','equipo_limpieza','otro')),
  unidad_medida  TEXT NOT NULL,
  costo_unitario NUMERIC(10,2) NOT NULL DEFAULT 0,
  activo         BOOLEAN NOT NULL DEFAULT TRUE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2) Existencias por sucursal (saldo vivo, lo mantiene el trigger)
CREATE TABLE IF NOT EXISTS insumo_existencias (
  insumo_id     INT NOT NULL REFERENCES insumos(id) ON DELETE CASCADE,
  sucursal_id   INT NOT NULL REFERENCES sucursales(id),
  stock_actual  NUMERIC(12,3) NOT NULL DEFAULT 0,
  stock_minimo  NUMERIC(12,3) NOT NULL DEFAULT 0,
  stock_reorden NUMERIC(12,3),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (insumo_id, sucursal_id)
);

-- 3) Receta de consumo (BOM) por tipo de servicio (valores reales de servicios.tipo)
CREATE TABLE IF NOT EXISTS consumo_estandar (
  id                    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_servicio         TEXT NOT NULL CHECK (tipo_servicio IN ('LIMPIEZA','ENTREGA','RETIRO','INSPECCION','EXTRA')),
  insumo_id             INT NOT NULL REFERENCES insumos(id) ON DELETE CASCADE,
  cantidad_por_servicio NUMERIC(12,3) NOT NULL CHECK (cantidad_por_servicio >= 0),
  UNIQUE (tipo_servicio, insumo_id)
);

-- 4) Ledger de movimientos (fuente de verdad)
CREATE TABLE IF NOT EXISTS movimientos_insumo (
  id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  insumo_id          INT NOT NULL REFERENCES insumos(id),
  sucursal_id        INT NOT NULL REFERENCES sucursales(id),
  tipo               TEXT NOT NULL CHECK (tipo IN ('entrada','salida','ajuste')),
  cantidad           NUMERIC(12,3) NOT NULL,
  origen             TEXT NOT NULL CHECK (origen IN ('cierre_ruta','cierre_jornada','compra','ajuste_manual','merma','inventario_fisico')),
  ruta_id            INT REFERENCES rutas(id),
  operador_id        INT REFERENCES operadores(id),
  fecha_jornada      DATE,
  servicios_contados INT NOT NULL DEFAULT 0,
  costo_total        NUMERIC(12,2) NOT NULL DEFAULT 0,
  nota               TEXT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT mov_cantidad_valida CHECK (
    (tipo = 'ajuste' AND cantidad <> 0) OR
    (tipo IN ('entrada','salida') AND cantidad > 0)
  )
);
CREATE INDEX IF NOT EXISTS idx_mov_insumo_suc ON movimientos_insumo (insumo_id, sucursal_id);
CREATE INDEX IF NOT EXISTS idx_mov_ruta       ON movimientos_insumo (ruta_id);
CREATE INDEX IF NOT EXISTS idx_mov_fecha      ON movimientos_insumo (created_at);
-- Idempotencia: una ruta no descuenta el mismo insumo dos veces
CREATE UNIQUE INDEX IF NOT EXISTS uniq_salida_ruta_insumo
  ON movimientos_insumo (ruta_id, insumo_id) WHERE origen = 'cierre_ruta';

-- 5) Consumo real declarado por el operador (override del BOM), por ruta
CREATE TABLE IF NOT EXISTS consumo_declarado (
  ruta_id   INT NOT NULL REFERENCES rutas(id) ON DELETE CASCADE,
  insumo_id INT NOT NULL REFERENCES insumos(id),
  cantidad  NUMERIC(12,3) NOT NULL CHECK (cantidad >= 0),
  PRIMARY KEY (ruta_id, insumo_id)
);

-- 6) Banderas de sincronización en el registro de rutas completadas
ALTER TABLE rutas
  ADD COLUMN IF NOT EXISTS insumos_procesados BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS procesado_en       TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS costo_insumos      NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE servicios
  ADD COLUMN IF NOT EXISTS insumos_descontados BOOLEAN NOT NULL DEFAULT FALSE;

-- 7) RLS + política staff_full_access (igual que el resto de tablas de GP)
ALTER TABLE insumos             ENABLE ROW LEVEL SECURITY;
ALTER TABLE insumo_existencias  ENABLE ROW LEVEL SECURITY;
ALTER TABLE consumo_estandar    ENABLE ROW LEVEL SECURITY;
ALTER TABLE movimientos_insumo  ENABLE ROW LEVEL SECURITY;
ALTER TABLE consumo_declarado   ENABLE ROW LEVEL SECURITY;
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['insumos','insumo_existencias','consumo_estandar','movimientos_insumo','consumo_declarado'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS staff_full_access ON %I', t);
    EXECUTE format('CREATE POLICY staff_full_access ON %I FOR ALL TO authenticated USING (true) WITH CHECK (true)', t);
  END LOOP;
END $$;

-- 8) Trigger: mantener insumo_existencias desde el ledger
CREATE OR REPLACE FUNCTION aplicar_movimiento_insumo()
RETURNS TRIGGER AS $$
DECLARE v_delta NUMERIC(12,3);
BEGIN
  v_delta := CASE NEW.tipo
               WHEN 'entrada' THEN  NEW.cantidad
               WHEN 'salida'  THEN -NEW.cantidad
               WHEN 'ajuste'  THEN  NEW.cantidad
             END;
  INSERT INTO insumo_existencias (insumo_id, sucursal_id, stock_actual, updated_at)
  VALUES (NEW.insumo_id, NEW.sucursal_id, v_delta, now())
  ON CONFLICT (insumo_id, sucursal_id) DO UPDATE
    SET stock_actual = insumo_existencias.stock_actual + v_delta,
        updated_at   = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_aplicar_movimiento ON movimientos_insumo;
CREATE TRIGGER trg_aplicar_movimiento
  AFTER INSERT ON movimientos_insumo
  FOR EACH ROW EXECUTE FUNCTION aplicar_movimiento_insumo();
